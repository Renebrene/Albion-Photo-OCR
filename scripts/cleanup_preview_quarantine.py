#!/usr/bin/env python3
"""Retention cleanup for the preview quarantine directory.

Preview files whose originals went missing are MOVED here by
``scripts/cleanup_missing_originals.py`` (never deleted in place) so the
action stays reversible.  This script is the reversible part's reverse: after
``--older-than-days`` (default 10, the maintenance cadence requested by the
owner) quarantined files are removed.

Caveat, kept in the docstring on purpose: a quarantined preview is the last
image of that photo while its original is gone.  Deleting it means the photo
keeps its row, description and verdict but loses the visible image until the
original returns (the preview can then be regenerated by
``scripts/rebuild_previews.py``).

Files younger than the threshold are always kept, so a recent cleanup can be
inspected and reverted by hand within the window.  Only paths inside
SCENE_PREVIEW_ROOT / data/preview_quarantine are touched.

Examples
--------
    .venv/bin/python scripts/cleanup_preview_quarantine.py --dry-run
    .venv/bin/python scripts/cleanup_preview_quarantine.py --json
    .venv/bin/python scripts/cleanup_preview_quarantine.py --older-than-days 10
"""

from __future__ import annotations

import argparse
import json
import os
import shutil
import sys
import time
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(REPO))

DEFAULT_QUARANTINE = REPO / "data" / "preview_quarantine"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--dry-run", action="store_true")
    parser.add_argument("--older-than-days", type=int, default=10)
    parser.add_argument("--max-delete", type=int, default=20000)
    parser.add_argument("--root", type=Path, default=DEFAULT_QUARANTINE)
    parser.add_argument("--json", action="store_true")
    args = parser.parse_args(argv)

    root = args.root.expanduser().resolve()
    cutoff = time.time() - max(0, int(args.older_than_days)) * 86400

    removed = 0
    removed_bytes = 0
    kept_recent = 0
    samples: list[str] = []
    limited = False

    if root.is_dir():
        for path in sorted(root.rglob("*")):
            if not path.is_file():
                continue
            try:
                mtime = path.stat().st_mtime
                size = path.stat().st_size
            except OSError:
                continue
            if mtime > cutoff:
                kept_recent += 1
                continue
            if removed >= args.max_delete:
                limited = True
                break
            if args.dry_run:
                removed += 1
                removed_bytes += size
            else:
                try:
                    path.unlink()
                    removed += 1
                    removed_bytes += size
                except OSError:
                    continue
            if len(samples) < 10:
                samples.append(str(path.relative_to(root)))

    # Пустые каталоги после удаления убираем, но только внутри карантина.
    if not args.dry_run and root.is_dir():
        for directory in sorted(root.rglob("*"), reverse=True):
            if directory.is_dir():
                try:
                    directory.rmdir()
                except OSError:
                    pass

    report = {
        "root": str(root),
        "older_than_days": args.older_than_days,
        "removed": removed,
        "removed_bytes": removed_bytes,
        "kept_recent": kept_recent,
        "limited": limited,
        "dry_run": args.dry_run,
        "samples": samples,
    }

    if args.json:
        print(json.dumps(report, ensure_ascii=False))
    else:
        action = "будет удалено" if args.dry_run else "удалено"
        print(f"карантин превью: {action} {removed} файлов "
              f"({removed_bytes / 1024 / 1024:.1f} МБ)")
        print(f"  моложе {args.older_than_days} дн. оставлено: {kept_recent}")
        if limited:
            print(f"  достигнут предел {args.max_delete}, запустите ещё раз")

    return 0


if __name__ == "__main__":
    raise SystemExit(main())
