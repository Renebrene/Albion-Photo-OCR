/**
 * Адрес для перезагрузки с обходом кеша.
 *
 * Обычный `location.reload()` перепроверяет оболочку, но если между браузером
 * и сервером есть кеширующий слой (прокси, туннель, «офлайн-кеш» браузера),
 * вкладка снова получает старый index.html — и подсказка «Доступна новая
 * сборка» повторяется бесконечно, хотя сборка на сервере уже другая
 * (28.10.2026). Уникальный параметр делает адрес новым, поэтому оболочка
 * запрашивается заново, а вместе с ней приходят новые хешированные бандлы.
 *
 * Параметр `_v` приложение не читает: фильтры в адресе живут под своими
 * именами, чужие ключи игнорируются.
 */
export function cacheBustUrl(href, token) {
  const url = new URL(href)

  url.searchParams.set('_v', String(token))

  return url.toString()
}
