-- Индексы для сортировок грида, которым не хватало порядка.
--
-- Замер на рабочей базе (56 870 фото, включён фильтр «распознанные» — 18 271
-- строка, лучший из трёх прогонов):
--
--   сортировка по имени файла   2 730 мс -> 19 мс
--   сортировка по дате          2 696 мс -> 22 мс
--
-- Причина: `ORDER BY` применялся к производной таблице (`_PHOTO_DERIVED`
-- поверх `_PHOTO_BASE`, где на каждую строку считаются шесть коррелированных
-- подзапросов), и без индекса, дающего порядок, до `LIMIT 101` материализовались
-- все строки. С индексом планировщик идёт по порядку и останавливается,
-- набрав 100 распознанных строк — подзапросы считаются сотни раз вместо
-- 56 тысяч (было 1 930 548 обращений к буферам). Именно поэтому сортировка по
-- `photo_id` всегда была быстрой: порядок давал первичный ключ.
--
-- Сортировки по адресу и по клиенту эти индексы не ускоряют: их ключ
-- собирается из справочника адресов и `photo_qwen`, одним индексом такой
-- порядок не задать. Там нужен отдельный разбор.
--
-- `IF NOT EXISTS` — миграция безопасна для повторного запуска.
--
-- Откат:
--   DROP INDEX public.idx_photos_sort_filename;
--   DROP INDEX public.idx_photos_sort_date;

CREATE INDEX IF NOT EXISTS idx_photos_sort_filename
    ON public.photos (filename, photo_id);

-- Выражение обязано совпадать с ключом сортировки в _SORT_EXPRESSIONS["date"].
CREATE INDEX IF NOT EXISTS idx_photos_sort_date
    ON public.photos (COALESCE(taken_at, created_at), photo_id);
