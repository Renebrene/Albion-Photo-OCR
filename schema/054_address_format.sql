-- Формат носителя в справочнике адресов («Экран», «Малый формат», …).
--
-- Приходит из того же XLS, что и сами адреса; в схеме 022 этой колонки не было.
-- Пустая строка означает «не указан», поэтому NOT NULL DEFAULT '' оставляет
-- существующие строки валидными без переписывания данных.
--
-- Миграция аддитивная: колонка добавляется, ничего не переименовывается и не
-- удаляется. XLS без колонки «Формат» импортируется как раньше — поле просто
-- остаётся пустым.
--
-- Откат: ALTER TABLE public.address_directory DROP COLUMN IF EXISTS format;

ALTER TABLE public.address_directory
    ADD COLUMN IF NOT EXISTS format TEXT NOT NULL DEFAULT '';
