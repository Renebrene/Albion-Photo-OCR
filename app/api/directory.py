"""
Address directory (schema/022): human-readable names for fingerprint ids.

The recognition pipeline writes a technical id into photos.address (the HYBRID
verdict, e.g. '83_v33'). The directory maps that id to the names people use:

    legal_address  - the official name (reports, contracts, download names);
    simple_address - the short name (grid checkboxes, lists).

The mapping is read-only for the photo API (it joins the two directory tables
when a photo row is built); this module only maintains the directory itself.

All queries are parameterised; nothing here reads image files.
"""

from __future__ import annotations

import re

from app.api.fingerprints import address_label
from app.ingest.database import get_connection

# Fingerprint ids are generated by the recognition pipeline; bound what the
# directory accepts so a request cannot store arbitrary text.
FINGERPRINT_ID_RE = re.compile(r"^[A-Za-z0-9._-]{1,64}$")

MAX_NAME_LENGTH = 300
MAX_SORT_ORDER = 100000


class DirectoryError(ValueError):
    """A request the directory refuses (bad name, duplicate, unknown row)."""


def _clean_name(value: object, *, field: str) -> str:
    if value is None:
        return ""

    if not isinstance(value, str):
        raise DirectoryError(f"{field} must be a string")

    text = " ".join(value.split())

    if len(text) > MAX_NAME_LENGTH:
        raise DirectoryError(f"{field} is too long")

    return text


def _check_fingerprint_id(fingerprint_id: object) -> str:
    if not isinstance(fingerprint_id, str) or not FINGERPRINT_ID_RE.match(
        fingerprint_id
    ):
        raise DirectoryError(
            "fingerprint id must be 1-64 characters of latin letters, digits,"
            " '.', '_' or '-' (the UI generates one by transliteration)"
        )

    return fingerprint_id


def list_addresses() -> list[dict]:
    """Every address with the fingerprint ids mapped to it."""

    with get_connection() as conn:
        with conn.cursor() as cur:
            cur.execute(
                """
                SELECT
                    d.address_id,
                    d.legal_address,
                    d.simple_address,
                    d.format,
                    d.active,
                    d.sort_order,
                    COALESCE(
                        array_agg(f.fingerprint_id ORDER BY f.fingerprint_id)
                            FILTER (WHERE f.fingerprint_id IS NOT NULL),
                        '{}'
                    ) AS fingerprints
                FROM public.address_directory AS d
                LEFT JOIN public.address_fingerprints AS f
                       ON f.address_id = d.address_id AND f.active
                GROUP BY d.address_id
                ORDER BY d.sort_order, d.address_id
                """
            )
            rows = cur.fetchall()

    return [
        {
            "address_id": int(row[0]),
            "legal_address": row[1],
            "simple_address": row[2],
            "format": row[3] or "",
            "active": bool(row[4]),
            "sort_order": int(row[5]),
            "fingerprints": list(row[6]),
        }
        for row in rows
    ]


def get_address(address_id: int) -> dict | None:
    for item in list_addresses():
        if item["address_id"] == address_id:
            return item

    return None


def fingerprint_map(active_only: bool = True) -> dict[str, dict]:
    """{fingerprint_id: {address_id, legal_address, simple_address}}."""

    where = "WHERE f.active AND d.active" if active_only else ""

    with get_connection() as conn:
        with conn.cursor() as cur:
            cur.execute(
                f"""
                SELECT f.fingerprint_id, d.address_id, d.legal_address,
                       d.simple_address
                FROM public.address_fingerprints AS f
                JOIN public.address_directory AS d
                  ON d.address_id = f.address_id
                {where}
                """
            )
            rows = cur.fetchall()

    return {
        row[0]: {
            "address_id": int(row[1]),
            "legal_address": row[2],
            "simple_address": row[3],
        }
        for row in rows
    }


def unassigned_fingerprints(known: list[str]) -> list[str]:
    """Fingerprint ids that exist in the pipeline but have no address yet."""

    mapped = set(fingerprint_map(active_only=False))

    return [item for item in known if item not in mapped]


def create_address(
    *,
    legal_address: object = None,
    simple_address: object = None,
    sort_order: object = 0,
) -> dict:
    """Create one address; raises DirectoryError when the input is unusable."""

    legal = _clean_name(legal_address, field="legal_address")
    simple = _clean_name(simple_address, field="simple_address")

    if not legal and not simple:
        raise DirectoryError("an address needs a legal or a simple name")

    try:
        order = int(sort_order) if sort_order is not None else 0
    except (TypeError, ValueError) as exc:
        raise DirectoryError("sort_order must be an integer") from exc

    if not -MAX_SORT_ORDER <= order <= MAX_SORT_ORDER:
        raise DirectoryError("sort_order is out of range")

    with get_connection() as conn:
        with conn.cursor() as cur:
            try:
                cur.execute(
                    """
                    INSERT INTO public.address_directory
                        (legal_address, simple_address, sort_order)
                    VALUES (%s, %s, %s)
                    RETURNING address_id
                    """,
                    (legal, simple, order),
                )
            except Exception as exc:
                message = str(exc)

                if "uq_address_directory_legal" in message:
                    raise DirectoryError(
                        "an address with this legal name already exists"
                    ) from exc

                raise

            address_id = int(cur.fetchone()[0])

    return get_address(address_id)


def update_address(
    address_id: int,
    *,
    legal_address: object = None,
    simple_address: object = None,
    active: object = None,
    sort_order: object = None,
) -> dict | None:
    """Update the supplied fields only; None fields keep their value."""

    assignments: list[str] = []
    params: list[object] = []

    if legal_address is not None:
        assignments.append("legal_address = %s")
        params.append(_clean_name(legal_address, field="legal_address"))

    if simple_address is not None:
        assignments.append("simple_address = %s")
        params.append(_clean_name(simple_address, field="simple_address"))

    if active is not None:
        assignments.append("active = %s")
        params.append(bool(active))

    if sort_order is not None:
        try:
            order = int(sort_order)
        except (TypeError, ValueError) as exc:
            raise DirectoryError("sort_order must be an integer") from exc

        if not -MAX_SORT_ORDER <= order <= MAX_SORT_ORDER:
            raise DirectoryError("sort_order is out of range")

        assignments.append("sort_order = %s")
        params.append(order)

    if not assignments:
        return get_address(address_id)

    assignments.append("updated_at = CURRENT_TIMESTAMP")
    params.append(address_id)

    with get_connection() as conn:
        with conn.cursor() as cur:
            # The name a fingerprint may have copied from this address.
            cur.execute(
                "SELECT legal_address, simple_address "
                "FROM public.address_directory WHERE address_id = %s",
                (address_id,),
            )
            current = cur.fetchone()

            if current is None:
                return None

            previous_label = address_label(current[1], current[0])

            try:
                cur.execute(
                    "UPDATE public.address_directory "
                    "SET " + ", ".join(assignments) + " WHERE address_id = %s",
                    params,
                )
            except Exception as exc:
                message = str(exc)

                if "uq_address_directory_legal" in message:
                    raise DirectoryError(
                        "an address with this legal name already exists"
                    ) from exc

                raise

            if cur.rowcount != 1:
                return None

            if legal_address is not None or simple_address is not None:
                cur.execute(
                    "SELECT legal_address, simple_address "
                    "FROM public.address_directory WHERE address_id = %s",
                    (address_id,),
                )
                renamed = cur.fetchone()
                new_label = address_label(renamed[1], renamed[0])

                if new_label != previous_label:
                    # Fingerprints take their name from here (set_address keeps
                    # the alias in display_name): rename those that still carry
                    # the name copied from this address. A name typed by hand is
                    # left alone.
                    cur.execute(
                        """
                        UPDATE public.fingerprints AS f
                        SET display_name = %s, updated_at = CURRENT_TIMESTAMP
                        FROM public.address_fingerprints AS af
                        WHERE af.fingerprint_id = f.fingerprint_id
                          AND af.address_id = %s
                          AND (f.display_name = '' OR f.display_name = %s)
                        """,
                        (new_label, address_id, previous_label),
                    )

    return get_address(address_id)


def delete_address(address_id: int) -> bool:
    """Delete an address; its fingerprint mappings go with it (CASCADE)."""

    with get_connection() as conn:
        with conn.cursor() as cur:
            cur.execute(
                "DELETE FROM public.address_directory WHERE address_id = %s",
                (address_id,),
            )
            return cur.rowcount == 1


def set_fingerprints(address_id: int, fingerprint_ids: list[str]) -> dict | None:
    """
    Replace the fingerprint ids mapped to *address_id*.

    An id belongs to exactly one address, so ids listed here are moved from
    whatever address they were on before; ids that were on this address but are
    not listed are unmapped. Runs in one transaction.
    """

    if not isinstance(fingerprint_ids, list):
        raise DirectoryError("fingerprints must be a list")

    ids = sorted({_check_fingerprint_id(item) for item in fingerprint_ids})

    if len(ids) > 500:
        raise DirectoryError("too many fingerprints")

    with get_connection() as conn:
        with conn.cursor() as cur:
            cur.execute(
                "SELECT 1 FROM public.address_directory WHERE address_id = %s",
                (address_id,),
            )

            if cur.fetchone() is None:
                return None

            cur.execute(
                "DELETE FROM public.address_fingerprints WHERE address_id = %s",
                (address_id,),
            )

            if ids:
                cur.executemany(
                    """
                    INSERT INTO public.address_fingerprints
                        (fingerprint_id, address_id)
                    VALUES (%s, %s)
                    ON CONFLICT (fingerprint_id) DO UPDATE
                       SET address_id = EXCLUDED.address_id,
                           updated_at = CURRENT_TIMESTAMP
                    """,
                    [(item, address_id) for item in ids],
                )

    return get_address(address_id)


