# Column titles people actually use; matching is case- and space-insensitive.
_LEGAL_HEADERS = {
    "юридический адрес",
    "юридическое название",
    "юридический",
    "наименование",
    "адрес",
    "address",
    "legal_address",
    "legal address",
    "legal",
}

_SIMPLE_HEADERS = {
    "упрощённый адрес",
    "упрощенный адрес",
    "упрощённое",
    "упрощенное",
    "краткое название",
    "alias",
    "simple_address",
    "simple address",
    "simple",
}

# Формат носителя (schema/054): «Экран», «Малый формат», «РнД» …
# Колонка необязательная: файлы без неё импортируются как раньше.
# Наборы и мягкие правила взяты из парсера «Локатора»
# (albion-locator-autonom/src/xls_import.py): там та же выгрузка «Рекламные
# возможности», где шапка стоит на 12-й строке, а колонка называется
# «Формат конструкции».
_FORMAT_HEADERS = {
    "формат",
    "формат конструкции",
    "тип конструкции",
    "вид конструкции",
    "конструкция",
    "format",
}

# Шапка не обязана быть первой строкой: в выгрузках перед ней идут заголовок
# отчёта, легенда и пустые строки. Ищем её в первых строках, как «Локатор».
MAX_HEADER_SCAN_ROWS = 100


def _normalize_header(value: str) -> str:
    text = " ".join(str(value).replace("\xa0", " ").split()).lower().replace("ё", "е")
    text = re.sub(r"[^\w\s.-]", " ", text)
    return " ".join(text.split())


def _header_kind(title: str) -> str | None:
    """К какому полю относится заголовок колонки (None — не наше)."""

    norm = _normalize_header(title)

    if not norm:
        return None
    if norm in _FORMAT_HEADERS or "формат" in norm:
        return "format"
    if norm in _SIMPLE_HEADERS or "упрощ" in norm:
        return "simple"
    if norm in _LEGAL_HEADERS or "юридическ" in norm or norm.startswith("наименован"):
        return "legal"
    return None


def _find_header(rows: list[list[str]]) -> tuple[int | None, dict[str, int]]:
    """Первая строка в первых MAX_HEADER_SCAN_ROWS, похожая на шапку."""

    for index, row in enumerate(rows[:MAX_HEADER_SCAN_ROWS]):
        mapping: dict[str, int] = {}

        for column, title in enumerate(row):
            kind = _header_kind(title)
            if kind and kind not in mapping:
                mapping[kind] = column

        if "legal" in mapping or "simple" in mapping:
            return index, mapping

    return None, {}

MAX_IMPORT_ROWS = 5000


def _cell(value: object) -> str:
    if value is None:
        return ""

    return " ".join(str(value).split()).strip()


def _rows_from_bytes(content: bytes, filename: str) -> list[list[str]]:
    """Raw rows from an .xlsx (openpyxl) or a text table (.csv/.tsv/.txt)."""

    name = (filename or "").lower()

    if name.endswith((".csv", ".tsv", ".txt")):
        import csv
        import io as _io

        text = None

        for encoding in ("utf-8-sig", "utf-8", "cp1251"):
            try:
                text = content.decode(encoding)
                break
            except UnicodeDecodeError:
                continue

        if text is None:
            raise DirectoryError("не удалось прочитать кодировку файла")

        sample = text[:4096]
        delimiter = "\t" if (name.endswith(".tsv") or sample.count("\t") > sample.count(",")) else ","

        rows = []

        for row in csv.reader(_io.StringIO(text), delimiter=delimiter):
            rows.append([_cell(cell) for cell in row])
            if len(rows) > MAX_IMPORT_ROWS:
                break

        return rows

    if not name.endswith((".xlsx", ".xlsm")):
        raise DirectoryError("поддерживаются файлы .xlsx, .xlsm, .csv, .tsv")

    import io as _io

    import openpyxl

    try:
        workbook = openpyxl.load_workbook(
            _io.BytesIO(content),
            read_only=True,
            data_only=True,
        )
    except Exception as exc:  # noqa: BLE001 - reported to the caller
        raise DirectoryError("файл не читается как XLSX") from exc

    sheet = workbook.active
    rows = []

    for row in sheet.iter_rows(values_only=True):
        rows.append([_cell(cell) for cell in row])

        if len(rows) > MAX_IMPORT_ROWS:
            break

    workbook.close()

    return rows


def parse_address_table(content: bytes, filename: str = "") -> list[dict]:
    """
    [{legal_address, simple_address}] from a spreadsheet.

    The header row is optional: when a column title is recognised, those columns
    are used; otherwise the first column is the legal address and the second the
    simplified one (a single column is legal-only).
    """

    rows = [row for row in _rows_from_bytes(content, filename) if any(row)]

    if not rows:
        return []

    header_index, mapping = _find_header(rows)

    if header_index is None:
        # Шапки нет: как раньше — первая колонка юридический адрес, вторая
        # упрощённый (если есть). «Формат» взять неоткуда.
        legal_index: int | None = 0
        simple_index: int | None = 1 if len(rows[0]) > 1 else None
        format_index = None
        body = rows
    else:
        legal_index = mapping.get("legal")
        simple_index = mapping.get("simple")
        format_index = mapping.get("format")

        if legal_index is None:
            legal_index = 0 if simple_index != 0 else None

        body = rows[header_index + 1:]

    items = []

    for row in body:
        legal = row[legal_index] if legal_index is not None and legal_index < len(row) else ""
        simple = (
            row[simple_index]
            if simple_index is not None and simple_index < len(row)
            else ""
        )
        value_format = (
            row[format_index]
            if format_index is not None and format_index < len(row)
            else ""
        )

        if not legal and not simple:
            continue

        # Ключ «format» появляется только когда колонка есть в файле: старые
        # выгрузки и тесты не обрастают пустым полем.
        item = {"legal_address": legal, "simple_address": simple}

        if value_format:
            item["format"] = value_format

        items.append(item)

    return items


def import_addresses(items: list[dict]) -> dict:
    """
    Create or update addresses from parsed rows.

    Rows are matched by the legal name (case- and whitespace-insensitive). An
    existing address keeps its id - photos and fingerprints mapped to it are not
    disturbed - and only its simplified name is refreshed when the file brings a
    different one.
    """

    if not isinstance(items, list):
        raise DirectoryError("ожидался список адресов")

    if len(items) > MAX_IMPORT_ROWS:
        raise DirectoryError("слишком много строк в файле")

    created = 0
    updated = 0
    skipped = 0
    renamed = 0
    errors: list[str] = []

    with get_connection() as conn:
        with conn.cursor() as cur:
            for item in items:
                try:
                    legal = _clean_name(item.get("legal_address"), field="legal_address")
                    simple = _clean_name(item.get("simple_address"), field="simple_address")
                    value_format = _clean_name(item.get("format"), field="format")
                except DirectoryError as exc:
                    errors.append(str(exc))
                    continue

                if not legal and not simple:
                    skipped += 1
                    continue

                existing = None

                if legal:
                    cur.execute(
                        """
                        SELECT address_id, simple_address, legal_address, format
                        FROM public.address_directory
                        WHERE lower(btrim(legal_address)) = lower(btrim(%s))
                        """,
                        (legal,),
                    )
                    existing = cur.fetchone()

                if existing is None:
                    cur.execute(
                        """
                        INSERT INTO public.address_directory
                            (legal_address, simple_address, format)
                        VALUES (%s, %s, %s)
                        """,
                        (legal, simple, value_format),
                    )
                    created += 1
                    continue

                address_id, current_simple, current_legal, current_format = existing

                updated_row = False

                if simple and simple != (current_simple or ""):
                    cur.execute(
                        """
                        UPDATE public.address_directory
                        SET simple_address = %s, updated_at = CURRENT_TIMESTAMP
                        WHERE address_id = %s
                        """,
                        (simple, address_id),
                    )
                    updated_row = True

                    # Слепки берут имя отсюда (`set_address` кладёт алиас в
                    # display_name). Переименование обязано доехать до них, как
                    # в `update_address`, иначе после переимпорта на слепке
                    # остаётся старое имя — и владелец «добавляет его заново».
                    # Имя, набранное руками, не трогаем.
                    previous_label = address_label(current_simple, current_legal)
                    new_label = address_label(simple, current_legal)

                    if new_label != previous_label:
                        cur.execute(
                            """
                            UPDATE public.fingerprints AS f
                            SET display_name = %s, updated_at = CURRENT_TIMESTAMP
                            FROM public.address_fingerprints AS af
                            WHERE af.fingerprint_id = f.fingerprint_id
                              AND af.address_id = %s
                              AND (f.display_name = '' OR f.display_name = %s)
                            """,
                            (new_label, address_id, previous_label),
                        )
                        renamed += cur.rowcount

                # Формат — такая же графа файла: обновляем, когда он есть и
                # отличается. Пустое значение в файле не стирает уже указанный.
                if value_format and value_format != (current_format or ""):
                    cur.execute(
                        """
                        UPDATE public.address_directory
                        SET format = %s, updated_at = CURRENT_TIMESTAMP
                        WHERE address_id = %s
                        """,
                        (value_format, address_id),
                    )
                    updated_row = True

                if updated_row:
                    updated += 1
                else:
                    skipped += 1

    return {
        "created": created,
        "updated": updated,
        "skipped": skipped,
        "renamed": renamed,
        "errors": errors[:20],
    }
